#!/usr/bin/env python3
"""Export season stgs assets (settings/itemflav/calevent/seasonNN.rpak) from common.rpak and build
the season -> guid64 / uniqueId / SAID table (docs/01-season-guids.md).

  python tools/export_season_guids.py
  python tools/export_season_guids.py --from-existing     (rebuild the table from files on disk)
  python tools/export_season_guids.py --dry-run

stgs header v2: +0 layout GUID, +8 value data, +16 name, +40 u32 uniqueId. uniqueId is the itemflavor id
generated by Bakery; the SAID string is "SAID" + uniqueId padded to 11 digits. The 64-bit asset GUID is
the --list csv "guid" column.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rsx_common import WORKSPACE, add_common_args, ensure_dir, load_guid_map, load_rsx_json, pad_guid64, pak, run_rsx  # noqa: E402

SEASON_RE = re.compile(r"^season(\d+)\.json$", re.I)
ASSET_DIR = Path("settings") / "itemflav" / "calevent"


def said(unique_id: int | str | None) -> str:
    if unique_id in (None, ""):
        return ""
    return f"SAID{int(unique_id):011d}"


def build_table(out_dir: Path) -> list[dict[str, str]]:
    guids = load_guid_map(out_dir / "season_stgs_filtered.csv")
    rows = []
    src = out_dir / ASSET_DIR
    if not src.is_dir():
        raise SystemExit(f"no exported seasons under {src} (run without --from-existing first)")
    for p in sorted(src.iterdir(), key=lambda x: x.name.lower()):
        m = SEASON_RE.match(p.name)
        if not m:
            continue
        data = load_rsx_json(p)
        uid = data.get("uniqueId")
        asset = (ASSET_DIR / (p.stem + ".rpak")).as_posix()
        rows.append({
            "season": p.stem,
            "guid64": pad_guid64(guids.get(asset.lower(), "")),
            "uniqueId": "" if uid is None else str(uid),
            "SAID": said(uid),
            "asset": asset,
        })
    rows.sort(key=lambda r: int(SEASON_RE.match(r["season"] + ".json").group(1)))
    return rows


def write_table(out_dir: Path, rows: list[dict[str, str]]) -> None:
    fields = ["season", "guid64", "uniqueId", "SAID", "asset"]
    csv_path = out_dir / "season_guids.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    txt_path = out_dir / "season_guids.txt"
    with txt_path.open("w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(f"{r['season']}\t{r['guid64']}\t{r['uniqueId']}\t{r['SAID']}\n")
    missing_guid = [r["season"] for r in rows if not r["guid64"]]
    missing_uid = [r["season"] for r in rows if not r["uniqueId"]]
    print(f"{len(rows)} seasons -> {csv_path}, {txt_path}")
    if missing_guid:
        print(f"  no guid in the --list csv for: {', '.join(missing_guid)}")
    if missing_uid:
        print(f"  no uniqueId in the json for: {', '.join(missing_uid)}")


def main() -> int:
    ap = add_common_args(argparse.ArgumentParser(description=__doc__))
    ap.add_argument("--pak", default="common.rpak", help="pak with the season stgs (default common.rpak)")
    args = ap.parse_args()
    out_dir = ensure_dir(args.out or (WORKSPACE / "exported_seasons"))

    if not args.from_existing:
        # Ptch: without it patch_master is ignored and the unpatched base pak is read.
        # stlt: the layouts are needed to turn stgs value data into JSON.
        run_rsx(
            args.rsx,
            [pak(args.paks, args.pak)],
            log_path=out_dir / "rsx_season_guids.log",
            loadwhitelist="stgs,stlt,Ptch",
            export=True,
            exporttypes="stgs",
            exportfilter=r"itemflav\calevent\season",
            exportdir=out_dir,
            list_path=out_dir / "season_stgs_filtered.csv",
            listformat="csv",
            parsethreads=args.parsethreads,
            dry_run=args.dry_run,
        )
        if args.dry_run:
            return 0

    write_table(out_dir, build_table(out_dir))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
